function kebab(name) {
  return name
    .replace(/\([^)]*\)/g, '')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .toLowerCase();
}

function parseDurationHours(label) {
  if (!label) return undefined;
  const l = label.toLowerCase();
  const hourMatch = l.match(/(\d+(?:\.\d+)?)\s*hours?/);
  if (l.includes('two 4.5-hour days') || l.includes('two 4.5 hour days')) return 9;
  if (l.includes('three 4.5-hour days')) return 13.5;
  if (l.includes('four 4.5-hour days')) return 18;
  if (l.includes('two 6-hour days')) return 12;
  if (l.includes('three 6-hour days')) return 18;
  if (l.includes('five 8-hour days')) return 40;
  if (l.includes('one 6-hour day')) return 6;
  if (l.includes('one 4.5-hour day')) return 4.5;
  if (l.includes('24 hours')) return 24;
  if (l.match(/1-3 hours/)) return 2;
  if (l.match(/3-4 hours/)) return 3.5;
  if (hourMatch) return parseFloat(hourMatch[1]);
  return undefined;
}

function parseCostUnits(str) {
  if (!str || /not available|n\/a/i.test(str)) return {};
  const costMatch = str.match(/\$([0-9,]+(?:\.[0-9]{2})?)/);
  const unitsMatch = str.match(/(\d+)\s*units?/i);
  const out = {};
  if (costMatch) out.cost = parseFloat(costMatch[1].replace(/,/g, ''));
  if (unitsMatch) out.units = parseInt(unitsMatch[1], 10);
  return out;
}

